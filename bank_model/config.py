"""Параметри імітаційної моделі роботи філії банку з п'ятьма касами.

Одиниця модельного часу: 1 хвилина.
"""
from dataclasses import dataclass


@dataclass
class Params:
    # Тривалість моделювання (робочий день 9:00-17:00), хв
    sim_time: float = 480.0

    # Вхідний потік клієнтів: пуассонівський,
    # інтервали між приходами мають експоненційний розподіл із середнім arrival_mean
    arrival_mean: float = 4.0          # хв  (λ = 1 / 4 = 0.25 клієнта/хв)

    # Термінал електронної черги (видача талонів): рівномірний розподіл
    use_terminal: bool = True
    terminal_min: float = 0.3          # хв
    terminal_max: float = 0.7          # хв

    # Каси: час обслуговування має експоненційний розподіл
    n_cashiers: int = 5                # кількість кас
    service_mean: float = 15.0         # хв  (μ = 1 / 15 клієнта/хв для однієї каси)

    # Кількість місць для очікування в операційному залі
    # (якщо всі місця зайняті, клієнт іде, тобто отримує відмову)
    queue_capacity: int = 30

    # Зерно генератора випадкових чисел (для кожного прогону своє)
    seed: int = 1

    @property
    def lam(self) -> float:
        """Інтенсивність вхідного потоку λ, клієнтів/хв."""
        return 1.0 / self.arrival_mean

    @property
    def mu(self) -> float:
        """Інтенсивність обслуговування однієї каси μ, клієнтів/хв."""
        return 1.0 / self.service_mean
